import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { chromium, expect } from "playwright/test";
import { createApp } from "../server/app.ts";
import { allowDemoShoppers } from "../server/auth.ts";
import { Store } from "../server/store.ts";
import { seedRestaurantDemo } from "./seed-restaurant-demo.ts";

process.env.DEMO_MODE = "true";
allowDemoShoppers();
const store = new Store(":memory:");
await seedRestaurantDemo(store, new Date());
const infoShop = (await store.list("shop")).find(shop => shop.slug === "kanton-ryu");
infoShop.published = { ...infoShop.published, reservationsEnabled: false, seating: undefined, menus: [] };
await store.saveShop(infoShop);
// Restaurant guests must also work when the demo's shared customer is disabled.
process.env.DEMO_MODE = "false";
const server = createApp(store);
await new Promise(resolve => server.listen(0, "127.0.0.1", resolve));
const origin = `http://127.0.0.1:${server.address().port}`;
process.env.APP_ORIGIN = origin;
let browser;
try {
  browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM ? { executablePath: process.env.CHROMIUM } : {}), args: ["--no-sandbox"] });
  await mkdir("tmp/reservation-sidebar", { recursive: true });
  for (const lang of ["ja", "en"]) for (const width of [1440, 390]) {
    const context = await browser.newContext({ viewport: { width, height: 900 }, locale: lang === "ja" ? "ja-JP" : "en-US" });
    const page = await context.newPage();
    const errors = [], calls = [];
    page.on("pageerror", error => errors.push(error.message));
    await context.route("https://**/models", route => route.fulfill({ contentType: "application/json", body: '{"data":[]}' }));
    await context.route("https://**/chat/completions", route => {
      calls.push(route.request());
      const chunk = { choices: [{ index: 0, delta: { content: "Sidebar fixture reply." }, finish_reason: null }] };
      return route.fulfill({ contentType: "text/event-stream", body: `data: ${JSON.stringify(chunk)}\n\ndata: [DONE]\n\n` });
    });
    const ready = () => page.waitForFunction(() => !!window.__nsweb?.engine && !document.getElementById("ai-settings-open").disabled);
    const path = lang === "en" ? "/s/akari" : "/s/akari/reserve";
    await page.goto(`${origin}${path}?lang=${lang}`);
    await ready();
    const panel = page.locator("#assistant"), toggle = page.locator("#assistant-toggle"), modal = page.locator("#ai-setup-dialog");
    if (lang === "ja") await expect(page.locator("#reserve-form")).toBeVisible();
    else await expect(page.locator("#reserve-form")).toBeHidden();
    await expect(page.locator('#root[data-page="static-storefront"]')).toBeAttached();
    await expect(page.locator(".reserve-shell")).toHaveCount(0);
    await expect(page.locator('.public-auth, .public-nav a[href*="pane=mine"], .public-nav a[href*="pane=contact"]')).toHaveCount(0);
    await expect(page.locator("#reserve-result")).toBeHidden();
    await expect(page.locator("#reserve-error")).toBeHidden();
    await expect(panel).toBeHidden();
    await expect(toggle).toHaveAttribute("aria-expanded", "false");
    await expect(modal).toBeHidden();
    if (lang === "ja") {
      assert.equal(new URL(page.url()).pathname, "/s/akari/reserve");
      await expect(toggle).toHaveText("AIで予約する");
    }
    await toggle.click();
    await expect(panel).toBeVisible();
    await expect(modal).toBeVisible();
    assert.equal(await modal.evaluate(dialog => dialog.matches(":modal")), true);
    await page.locator("#ai-provider").selectOption("OpenRouter");
    await page.locator("#ns-key").fill("fixture-sidebar-key");
    await Promise.all([page.waitForNavigation(), page.locator("#ns-apply").click()]);
    await ready();
    await expect(panel).toBeVisible();
    await expect(modal).toBeHidden();
    await expect(page.locator("#agent-app .ns-agents")).toBeHidden();
    assert.ok(!(await panel.innerText()).includes("Agents working for you"));
    await expect(page.locator("#ns-newchat")).toBeHidden();
    assert.equal(await page.locator(".ns-inputbar #ns-newchat").count(), 0);
    await page.locator("#ns-input").fill("draft to preserve");
    await page.locator("#assistant-close").click();
    await expect(panel).toBeHidden();
    await expect(toggle).toBeFocused();
    await toggle.click();
    await expect(page.locator("#ns-input")).toHaveValue("draft to preserve");
    await page.locator("#ai-settings-open").click();
    await expect(modal).toBeVisible();
    await page.locator("#ai-provider").selectOption("Google AI Studio");
    await expect(page.locator("#ns-key")).toHaveValue("");
    // Discarding an edit restores the applied provider and cannot send its key elsewhere.
    await page.keyboard.press("Escape");
    await expect(modal).toBeHidden();
    await expect(panel).toBeVisible();
    await expect(page.locator("#ns-router")).toHaveValue("https://openrouter.ai/api/v1");
    await page.locator("#ns-input").fill("hello");
    await page.locator("#ns-send").click();
    await expect(page.locator("#ns-msgs")).toContainText("Sidebar fixture reply.");
    await expect(page.locator(".ns-inputbar")).toHaveAttribute("data-turn-active", "false");
    await page.locator(".assistant-chat-menu > summary").click();
    await expect(page.locator("#ns-newchat")).toBeVisible();
    await page.locator("#ns-newchat").click();
    await expect(page.locator("#ns-msgs")).not.toContainText("Sidebar fixture reply.");
    await expect(page.locator("#ns-newchat")).toBeHidden();
    assert.equal(calls.length, 1);
    assert.equal(calls[0].headers().authorization, "Bearer fixture-sidebar-key");
    assert.equal(calls[0].url(), "https://openrouter.ai/api/v1/chat/completions");
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    const box = await panel.boundingBox();
    assert.ok(box.x >= 0 && box.x + box.width <= width + 1);
    await page.screenshot({ path: `tmp/reservation-sidebar/${lang}-${width}.png` });
    await page.locator("#ns-input").focus();
    await page.keyboard.press("Escape");
    await expect(panel).toBeHidden();
    await expect(page.locator("#reserve-date")).toBeEnabled();
    if (lang === "ja") await expect(page.locator("#reserve-form")).toBeVisible();
    else await expect(page.locator("#reserve-form")).toBeHidden();
    assert.equal(await page.locator(".reserve-shell, #root").first().evaluate(element => element.inert), false);
    assert.deepEqual(errors, []);
    await toggle.click();
    await expect(panel).toBeVisible();
    await page.goto(`${origin}/s/akari/reserve?lang=${lang}`);
    await ready();
    await expect(panel).toBeHidden();
    await expect(toggle).toHaveText(lang === "ja" ? "AIで予約する" : "Reserve with AI");
    await expect(page.locator("#reserve-form")).toBeVisible();
    // Booking works without an AI setup or any model call.
    await page.evaluate(() => { localStorage.clear(); sessionStorage.clear(); });
    await page.reload();
    await expect(page.locator("#assistant")).toBeHidden();
    await expect(page.locator("#reserve-result")).toBeHidden();
    await expect(page.locator("#reserve-error")).toBeHidden();
    const callsBeforeBooking = calls.length;
    const date = new Date(Date.now() + 7 * 86400000).toISOString().slice(0, 10);
    await page.locator("#reserve-date").fill(date);
    await page.locator("#reserve-people").fill("2");
    await page.locator("#reserve-people").press("Tab");
    await page.waitForFunction(() => [...document.querySelectorAll("#reserve-time option")].some(option => option.value && !option.disabled));
    const time = await page.locator("#reserve-time").evaluate(select => [...select.options].find(option => option.value && !option.disabled).value);
    await page.locator("#reserve-time").selectOption(time);
    await page.locator("#reserve-name").fill("フォーム予約テスト");
    await expect(page.locator("#reserve-email")).toHaveCount(0);
    await expect(page.locator("#reserve-phone")).toHaveAttribute("required", "");
    // Each language/viewport represents a different guest; do not consume another case's phone quota.
    await page.locator("#reserve-phone").fill(`031234${lang === "ja" ? "1" : "2"}${width === 1440 ? "111" : "222"}`);
    await page.locator('#reserve-form button[type="submit"]').click();
    await expect(page.locator("dialog.assistant-review")).toBeVisible();
    await page.locator(".assistant-confirm").click();
    await expect(page.locator("#reserve-result")).toBeVisible();
    await expect(page.locator("#reserve-result-title")).not.toBeEmpty();
    await expect(page.locator("#reserve-result-text")).not.toBeEmpty();
    assert.equal(calls.length, callsBeforeBooking);
    await expect(page.locator("#assistant")).toBeHidden();
    await page.screenshot({ path: `tmp/reservation-sidebar/form-booking-${lang}-${width}.png` });
    await page.goto(`${origin}/s/kanton-ryu?lang=${lang}`);
    await expect(page.locator('#root[data-page="static-storefront"]')).toBeVisible();
    await expect(page.locator('#reserve-form, #assistant-toggle, .public-auth, .public-nav a[href*="reserve"], .public-nav a[href*="pane=mine"], .public-nav a[href*="pane=contact"]')).toHaveCount(0);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: `tmp/reservation-sidebar/info-only-${lang}-${width}.png`, fullPage: true });
    await context.close();
    console.log(`${lang} ${width}px: reservation form without AI, optional chat, shared page design, modal setup and provider isolation passed.`);
  }
} finally {
  await browser?.close();
  server.closeAllConnections();
  await new Promise(resolve => server.close(resolve));
  await store.close();
}
